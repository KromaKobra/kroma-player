"""Base repository class for generic CRUD operations.

This module provides a generic, reusable base class for all data access objects.
Rather than writing the same CRUD methods in every repository, we define them once
here and inherit from BaseRepository.

Key principles:
- Type-safe: Uses TypeVar to support any model type
- Generic: Works with any SQLAlchemy ORM model
- Simple: Focused only on basic CRUD; business logic goes in services

Inheritance model:
    BaseRepository[Track] (this file)
         ↑
         |
    TrackRepository (track_repository.py)
         ↑
         |
    Services use TrackRepository for data access

Relationship to other modules:
- Models: Works with any SQLAlchemy model (Track, Artist, etc.)
- Sessions: Gets a session injected via constructor
- Services: Services call repository methods, not the other way around
"""
from typing import TypeVar, Generic, List, Optional
from sqlalchemy.orm import Session

T = TypeVar('T')


class BaseRepository(Generic[T]):
    """Generic base repository for CRUD operations on any SQLAlchemy model.

    This class provides basic database operations (Create, Read, Update, Delete)
    that work for any entity type. Subclasses add domain-specific queries.

    Type parameter:
        T: The SQLAlchemy ORM model class (e.g., Track, Artist)

    Example:
        class TrackRepository(BaseRepository[Track]):
            def __init__(self, session: Session):
                super().__init__(session, Track)

            def get_by_title(self, title: str) -> Optional[Track]:
                # Add custom queries here
                return self.session.query(self.model_class).filter_by(title=title).first()
    """

    def __init__(self, session: Session, model_class: type[T]):
        """Initialize repository.

        Args:
            session: SQLAlchemy Session for database operations
            model_class: The ORM model class this repository manages
        """
        self.session = session
        self.model_class = model_class

    def get_by_id(self, id: int) -> Optional[T]:
        """Get entity by primary key ID.

        Args:
            id: Primary key value

        Returns:
            The entity if found, None otherwise
        """
        return self.session.query(self.model_class).filter_by(id=id).first()

    def get_all(self, skip: int = 0, limit: int = 100) -> List[T]:
        """Get all entities with pagination.

        Args:
            skip: Number of records to skip (offset)
            limit: Maximum number of records to return

        Returns:
            List of entities (empty list if no results)
        """
        return self.session.query(self.model_class).offset(skip).limit(limit).all()

    def create(self, **kwargs) -> T:
        """Create and persist a new entity.

        This method creates a new instance of the model, adds it to the session,
        and commits immediately.

        Args:
            **kwargs: Keyword arguments to pass to the model constructor

        Returns:
            The newly created entity (with ID set by the database)

        Example:
            track = repository.create(title="Song", duration_seconds=180)
            # track.id is now set (auto-generated by database)
        """
        instance = self.model_class(**kwargs)
        self.session.add(instance)
        self.session.commit()
        return instance

    def update(self, id: int, **kwargs) -> Optional[T]:
        """Update an entity by ID.

        This method fetches the entity, updates its attributes, and commits.

        Args:
            id: Primary key of entity to update
            **kwargs: Attribute name -> new value pairs

        Returns:
            The updated entity, or None if entity was not found

        Example:
            track = repository.update(1, title="New Title", duration_seconds=200)
        """
        instance = self.get_by_id(id)
        if instance:
            for key, value in kwargs.items():
                setattr(instance, key, value)
            self.session.commit()
        return instance

    def delete(self, id: int) -> bool:
        """Delete an entity by ID.

        Args:
            id: Primary key of entity to delete

        Returns:
            True if entity was deleted, False if not found
        """
        instance = self.get_by_id(id)
        if instance:
            self.session.delete(instance)
            self.session.commit()
            return True
        return False

    def count(self) -> int:
        """Get total count of entities.

        Returns:
            Number of records in the table for this model
        """
        return self.session.query(self.model_class).count()
